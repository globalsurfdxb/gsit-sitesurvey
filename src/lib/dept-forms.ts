type Choice = Extract<BlockDef, { t: "choice" }>;

const YN = ["Yes", "No"];

const text = (key: string, label: string, placeholder?: string, required = false): BlockDef => ({ t: "text", key, label, ...(placeholder ? { placeholder } : {}), required });
const area = (key: string, label: string, placeholder?: string): BlockDef => ({ t: "textarea", key, label, ...(placeholder ? { placeholder } : {}), required: false });
const num = (key: string, label: string, placeholder?: string, required = false): BlockDef => ({ t: "number", key, label, ...(placeholder ? { placeholder } : {}), required });
const one = (key: string, label: string, options: string[], required = false): Choice => ({ t: "choice", key, label, options, multi: false, required });
const many = (key: string, label: string, options: string[], required = false): Choice => ({ t: "choice", key, label, options, multi: true, required });
const yn = (key: string, label: string): Choice => one(key, label, YN);
const heading = (text: string): BlockDef => ({ t: "heading", text });
const photos = (key: string, slots: [string, string][]): BlockDef => ({ t: "photos", key, slots: slots.map(([k, label]) => ({ key: k, label })) });

/** Client, contact and survey details shared by both forms. */
function details(tone: string): SectionDef {
  const internal = (name: string) => `client.gs_it_internal.${name}`;
  const client = (name: string) => `client.client_details.${name}`;
  return {
    key: "client",
    title: "Client information",
    subtitle: "Deal, contact & survey details",
    iconName: "briefcase",
    tone,
    short: "Client",
    scope: "always",
    blocks: [
      heading("GS IT internal"),
      text(internal("deal_id"), "Deal ID", "e.g. GS-2026-0001", true),
      text(internal("sales_person"), "Sales person", "Sales rep name", true),
      text(internal("survey_engineer"), "Survey engineer", "Engineer name", true),
      { t: "date", key: internal("survey_date"), label: "Survey date", required: true, defaultToday: true },
      heading("Client details"),
      text(client("client_name"), "Client / company", undefined, true),
      text(client("contact_person"), "Contact person", "Name and designation", true),
      text(client("contact_phone"), "Contact phone", "+971 …", true),
      text(client("contact_email"), "Contact email"),
      text(client("site_address"), "Site address", "Building name, floor, area, emirate", true),
    ],
  };
}

